"""Generate presentation-only Vietnamese catalogs from the pinned ERP sources.

Run in the bench Python environment (Babel is already provided by Frappe):
  env/bin/python apps/lotus_farm/tools/export_erp_vietnamese.py --bench-root .
Vendor PO translations retain their original Frappe/ERPNext/HRMS licenses.
Stored DocType/field/enum identifiers are never rewritten.
"""
import argparse
import csv
import json
import re
from pathlib import Path


def collect(bench, app_root):
    from babel.messages.pofile import read_po
    messages, terms, navigation = {}, set(), set()
    shared = {'Currency','Country','Address','Contact','Print Settings','System Settings','Letter Head','Print Heading','Email Account'}
    for app in ('frappe','erpnext','hrms'):
        root = bench / 'apps' / app / app
        for message in read_po((root / 'locale/vi.po').open('rb')):
            if isinstance(message.id, str) and isinstance(message.string, str) and message.string.strip() and message.id != message.string:
                messages[message.id] = message.string
        for source in root.glob('*/doctype/*/*.json'):
            doc = json.loads(source.read_text(encoding='utf-8'))
            if not isinstance(doc, dict) or app == 'frappe' and doc.get('name') not in shared:
                continue
            terms.add(doc.get('name', '')); navigation.add(doc.get('name', ''))
            for field in doc.get('fields', []):
                terms.update((field.get('label', ''), field.get('description', '')))
                if field.get('fieldtype') == 'Select':
                    terms.update((field.get('options') or '').split('\n'))
    for name, report in json.loads((app_root / 'lotus_farm/erp_report_metadata.json').read_text(encoding='utf-8'))['reports'].items():
        terms.add(name); navigation.add(name)
        for field in report.get('filters', []):
            terms.update((field.get('label', ''), field.get('description', '')))
            options = field.get('options')
            if field.get('fieldtype') in ('Select', 'Autocomplete'):
                terms.update(options.split('\n') if isinstance(options, str) else [s for s in options if isinstance(s, str)] if isinstance(options, list) else [])
    # Sidebar headings are source metadata, not business records.
    for app in ('erpnext','hrms'):
        for source in (bench / 'apps' / app / app).glob('*/workspace*/*/*.json'):
            try:
                doc = json.loads(source.read_text(encoding='utf-8'))
            except (ValueError, OSError):
                continue
            if isinstance(doc, dict):
                for row in doc.get('links', []):
                    if row.get('label'):
                        terms.add(row['label']); navigation.add(row['label'])
    return messages, terms, navigation


def generate(app_root, messages, terms, navigation):
    csv_path = app_root / 'lotus_farm/translations/vi.csv'
    # Preserve existing Lotus translations, including its business terminology.
    with csv_path.open(encoding='utf-8-sig', newline='') as stream:
        for row in csv.reader(stream):
            if len(row) >= 2 and row[1].strip():
                messages[row[0]] = row[1]
    for line in (app_root / 'lotus_farm/erp_vi_overrides.tsv').read_text(encoding='utf-8').splitlines():
        if '\t' in line:
            source, target = line.split('\t', 1)
            messages[source] = target
            terms.add(source); navigation.add(source)
    with csv_path.open('w', encoding='utf-8', newline='') as stream:
        csv.writer(stream, lineterminator='\n').writerows(sorted(messages.items()))
    for name, selected in (('erp-vi-messages.js', terms), ('erp-vi-navigation.js', navigation)):
        data = {key: messages[key] for key in sorted(selected) if key in messages}
        (app_root / 'frontend/src' / name).write_text('// Generated by tools/export_erp_vietnamese.py from the installed PO catalogs and Lotus overrides.\nexport default ' + json.dumps(data, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    missing = sorted(s for s in terms if isinstance(s, str) and re.search('[a-zA-Z]', s) and s not in messages and not re.fullmatch(r'[A-Z0-9_./:+# -]+', s))
    return dict(messages=len(messages), ui_terms=len(terms), missing=missing)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--bench-root', type=Path, default=Path.cwd())
    parser.add_argument('--app-root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--native-json', type=Path)
    parser.add_argument('--terms-json', type=Path)
    parser.add_argument('--navigation-json', type=Path)
    parser.add_argument('--audit', type=Path)
    args = parser.parse_args()
    if args.native_json:
        messages = json.loads(args.native_json.read_text(encoding='utf-8'))
        terms = set(json.loads(args.terms_json.read_text(encoding='utf-8')))
        navigation = set(json.loads(args.navigation_json.read_text(encoding='utf-8')))
    else:
        messages, terms, navigation = collect(args.bench_root, args.app_root)
    result = generate(args.app_root, messages, terms, navigation)
    if args.audit:
        args.audit.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({key:value if key != 'missing' else len(value) for key,value in result.items()}))
