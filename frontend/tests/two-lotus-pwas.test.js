import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

const repo=path.resolve(import.meta.dirname,'../..')
const read=file=>fs.readFileSync(path.join(repo,file),'utf8')
const warehouse=JSON.parse(read('lotus_farm/public/warehouse.webmanifest'))
const work=JSON.parse(read('lotus_farm/public/work.webmanifest'))
const ww=read('lotus_farm/public/warehouse-worker.js')
const vw=read('lotus_farm/public/work-worker.js')
const wr=read('frontend/src/register-warehouse-worker.js')
const vr=read('frontend/src/register-work-worker.js')
const entryWarehouse=read('frontend/src/warehouse-mobile-main.js')
const entryWork=read('frontend/src/work-mobile-main.js')
const backend=read('lotus_farm/web.py')

test('two Lotus PWAs have different stable manifest IDs, URLs and names',()=>{
 assert.equal(warehouse.id,'/warehouse')
 assert.equal(work.id,'/work')
 assert.equal(warehouse.start_url,'/warehouse')
 assert.equal(work.start_url,'/work')
 assert.equal(warehouse.scope,'/warehouse')
 assert.equal(work.scope,'/work')
 assert.notEqual(warehouse.name,work.name)
 assert.equal(warehouse.display,'standalone')
 assert.equal(work.display,'standalone')
})
test('two apps have distinct launcher icons that physically differ',()=>{
 for(const size of ['192','512']){
  const wh=warehouse.icons.find(i=>i.sizes===size+'x'+size)
  const wk=work.icons.find(i=>i.sizes===size+'x'+size)
  assert.ok(wh&&wk)
  assert.notEqual(wh.src,wk.src)
  const local=url=>'lotus_farm/public'+url.replace('/assets/lotus_farm','')
  const whFile=fs.readFileSync(path.join(repo,local(wh.src)))
  const wkFile=fs.readFileSync(path.join(repo,local(wk.src)))
  assert.ok(whFile.length>1000&&wkFile.length>1000)
  assert.equal(whFile.subarray(1,4).toString(),'PNG')
  assert.equal(wkFile.subarray(1,4).toString(),'PNG')
  assert.notDeepEqual(whFile,wkFile)
 }
})
test('two separate service worker URLs and security contexts',()=>{
 assert.match(wr,/warehouse_service_worker/)
 assert.match(vr,/work_service_worker/)
 assert.match(wr,/scope:'\/warehouse'/)
 assert.match(vr,/scope:'\/work'/)
 assert.match(wr,/window\.isSecureContext/)
 assert.match(vr,/window\.isSecureContext/)
 assert.match(wr,/updateViaCache:'none'/)
 assert.match(vr,/updateViaCache:'none'/)
 assert.match(backend,/'Service-Worker-Allowed':'\/warehouse'/)
 assert.match(backend,/'Service-Worker-Allowed': '\/work'/)
})
test('PWA installers and entrypoints are independent, with no cross-registration',()=>{
 assert.match(entryWarehouse,/WarehouseMobile/)
 assert.match(entryWork,/WorkMobile/)
 assert.match(entryWarehouse,/register-warehouse-worker/)
 assert.match(entryWork,/register-work-worker/)
 assert.doesNotMatch(entryWarehouse,/register-work-worker/)
 assert.doesNotMatch(entryWork,/register-warehouse-worker/)
})
test('each worker owns a namespaced cache and never caches authenticated API calls',()=>{
 assert.match(ww,/lotus-warehouse-shell-/)
 assert.match(vw,/lotus-work-shell-/)
 assert.match(ww,/caches\.open\(CACHE\)/)
 assert.match(vw,/caches\.open\(CACHE\)/)
 assert.match(ww,/startsWith\('lotus-warehouse-shell-'\)/)
 assert.match(vw,/startsWith\('lotus-work-'\)/)
 assert.match(ww,/pathname\.startsWith\('\/api\/'\)/)
 assert.match(vw,/pathname\.startsWith\('\/api\/'\)/)
 assert.match(ww,/ASSETS\.includes\(url\.pathname\)/)
 assert.match(vw,/ASSETS\.includes\(url\.pathname\)/)
 assert.match(ww,/==='\/warehouse'/)
 assert.match(vw,/==='\/work'/)
 assert.doesNotMatch(vw,/caches\.match\(e\.request\)/)
})
test('separate authenticated Frappe page shells point to their own manifest and app icon',()=>{
 const wHtml=read('lotus_farm/www/warehouse.html')
 const vHtml=read('lotus_farm/www/work.html')
 assert.match(wHtml,/lotus_farm\.web\.warehouse_manifest/)
 assert.match(vHtml,/lotus_farm\.web\.work_manifest/)
 assert.match(wHtml,/warehouse-icon-v3-192/)
 assert.match(vHtml,/work-icon-v3-192/)
 assert.match(backend,/def warehouse_manifest/)
 assert.match(backend,/def work_manifest/)
 assert.match(read('lotus_farm/www/warehouse.py'),/frappe\.session\.user == 'Guest'/)
 assert.match(read('lotus_farm/www/work.py'),/frappe\.session\.user == "Guest"/)
})
