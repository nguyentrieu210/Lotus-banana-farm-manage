import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'../..')
const read=(f)=>fs.readFileSync(path.join(root,f),'utf8')
test('Purchasing PWA has distinct route, manifest, worker and UI entrypoint',()=>{
  const manifest=JSON.parse(read('lotus_farm/public/buying.webmanifest'))
  assert.equal(manifest.start_url,'/buying')
  assert.equal(manifest.scope,'/buying')
  assert.notEqual(manifest.id,JSON.parse(read('lotus_farm/public/warehouse.webmanifest')).id)
  assert.match(read('frontend/vite.config.js'),/'buying.html'/)
  assert.match(read('lotus_farm/www/buying.py'),/buying\.html/)
  assert.match(read('lotus_farm/www/buying.html'),/buying_manifest/)
  assert.match(read('lotus_farm/public/buying-worker.js'),/startsWith\('\/api\/\'\)/)
  assert.match(read('frontend/src/register-buying-worker.js'),/scope:'\/buying'/)
})
test('ERP documents enforce an independent approver at server layer',()=>{
  const py=read('lotus_farm/purchasing.py')
  const hooks=read('lotus_farm/hooks.py')
  assert.match(hooks,/Purchase Order'\]=\{'before_submit':'lotus_farm.purchasing.check_submission'/)
  assert.match(py,/doc\.owner != frappe\.session\.user/)
  assert.match(py,/doc\.owner == frappe\.session\.user/)
  assert.match(py,/saved_state != PENDING/)
  assert.match(py,/doc\.submit\(\)/)
  assert.match(py,/def reject_order/)
  assert.match(py,/def request_approval/)
})
test('Warehouse creates a Material Request, not a Purchase Order',()=>{
  const vue=read('frontend/src/WarehouseMobile.vue')
  const py=read('lotus_farm/purchasing.py')
  assert.match(vue,/@select="startRequest"/)
  assert.match(vue,/call\('lotus_farm.purchasing.create_request'/)
  assert.match(py,/doctype="Material Request"/)
  assert.match(py,/material_request_type="Purchase"/)
  assert.match(vue,/Gửi đề nghị mua/)
})
test('Buyer supports supplier history, requests, pricing, approval and partial receiving',()=>{
  const vue=read('frontend/src/BuyingMobile.vue')
  const py=read('lotus_farm/purchasing.py')
  const shared=read('frontend/src/components/MobilePurchaseOrderDetail.vue')
  assert.match(vue,/<MobilePurchaseOrderDetail/)
  for(const s of ['Nhà cung cấp','Đề nghị mua','Đơn mua','Gửi duyệt đơn mua','Duyệt đơn mua','Trả lại đơn','Đã nhận','Tổng tiền'])assert.ok((vue+shared).includes(s),s)
  assert.match(py,/def save_supplier/)
  assert.match(py,/def orders/)
  assert.match(py,/def requests/)
  assert.match(read('lotus_farm/warehouse_buying_lite.py'),/received_qty/)
})

test('Installed buying app remains inside its scope when session expires',()=>{
  const page=read('lotus_farm/www/buying.py')
  const html=read('lotus_farm/www/buying.html')
  const worker=read('lotus_farm/public/buying-worker.js')
  const web=read('lotus_farm/web.py')
  assert.match(page,/context\.guest = frappe\.session\.user == "Guest"/)
  assert.doesNotMatch(page,/redirect_location/)
  assert.match(html,/{% if guest %}/)
  assert.match(html,/\/login\?redirect-to=%2Fbuying/)
  assert.match(worker,/Promise\.allSettled/)
  assert.match(worker,/cache:'no-store'/)
  assert.match(web,/methods=\['GET', 'HEAD'\]\)\ndef buying_manifest/)
  assert.match(web,/methods=\['GET', 'HEAD'\]\)\ndef buying_service_worker/)
})
