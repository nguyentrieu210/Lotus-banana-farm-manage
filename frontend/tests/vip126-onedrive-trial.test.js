import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const base=new URL('../../',import.meta.url)
const read=p=>readFileSync(new URL(p,base),'utf8')
test('Trial mode is the default and actual-only is still available',()=>{
 const c=read('frontend/src/components/Vip126RollingForecast.vue')
 assert.match(c,/mode=ref\('trial'\)/)
 assert.match(c,/Chạy thử đủ 64 lô/)
 assert.match(c,/Chỉ dữ liệu đang có/)
 assert.match(c,/lotus_farm\.vip126_trial\.calendar/)
 assert.match(c,/lotus_farm\.vip126_timeline\.calendar/)
 assert.match(c,/Chạy thử|THỬ NGHIỆM/)
 assert.match(c,/Cây giả lập/)
 assert.match(c,/Khu '/)
})
test('Trial allows what-if stage change without saving documents',()=>{
 const c=read('frontend/src/components/Vip126RollingForecast.vue')
 assert.match(c,/trial_block:trialBlock\.value/)
 assert.match(c,/trial_stage:trialStage\.value/)
 assert.match(c,/trial_date:trialDate\.value/)
 assert.match(c,/Tính lại 36 tháng/)
 const py=read('lotus_farm/vip126_trial.py')
 assert.match(py,/TEST_STAGES/)
 assert.match(py,/land_scope/)
 assert.match(py,/land_filters/)
 assert.match(py,/Harvest Forecast/)
 assert.match(py,/Farm Block/)
 assert.match(py,/commit_ready": False/)
 assert.doesNotMatch(py,/\.insert\(|\.save\(|set_value\(|frappe\.db\.set_value\(|frappe\.delete_doc\(/)
})
test('OneDrive 17kg is processed yield, no double QC/packout loss',()=>{
 const py=read('lotus_farm/vip126_trial.py')
 assert.match(py,/"packed_kg_per_processed_bunch": 17\./)
 assert.match(py,/"preprocess_rate": \.98/)
 assert.match(py,/preprocessed \* trial\["packed_kg_per_processed_bunch"\]/)
 assert.match(py,/never|Never/)
 assert.match(py,/synthetic_count_lots/)
 assert.match(py,/TRIAL_FLOWERING/)
 assert.match(py,/2026-11-01/)
})
