import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const app=readFileSync(new URL('../src/WarehouseMobile.vue',import.meta.url),'utf8')
const css=readFileSync(new URL('../src/warehouse-mobile.css',import.meta.url),'utf8')
const entry=readFileSync(new URL('../src/warehouse-mobile-main.js',import.meta.url),'utf8')
const page=readFileSync(new URL('../../lotus_farm/www/warehouse.py',import.meta.url),'utf8')
const workerRoute=readFileSync(new URL('../../lotus_farm/web.py',import.meta.url),'utf8')
test('PWA Kho uses independent mobile entry with simple forms and four mobile tabs',()=>{
 assert.match(entry,/WarehouseMobile/)
 assert.doesNotMatch(entry,/StockApp|stock-main/)
 assert.match(page,/include\('warehouse.html'\)/)
 assert.match(workerRoute,/add\('warehouse.html'\)/)
 for(const label of ['Nhập theo đơn','Nhập không theo đơn','Xuất kho','Chuyển kho','Tạo đơn mua','Lịch sử','Xuất nhập tồn','Tôi'])assert.ok(app.includes(label),label)
 assert.doesNotMatch(app,/DataTable|AGGrid|UiButton|frappe-ui/)
 assert.match(app,/<LotusMobileShell/)
 assert.match(app,/class="mobile-switcher"/)
 assert.doesNotMatch(app,/Kiểm kê/)
})
test('Mobile PWA uses compact shared logo, Vant navigation and tappable forms',()=>{
 const shared=readFileSync(new URL('../src/components/LotusMobileShell.vue',import.meta.url),'utf8')
 const header=readFileSync(new URL('../src/components/LotusMobileHeader.vue',import.meta.url),'utf8')
 const bottom=readFileSync(new URL('../src/components/LotusMobileBottomNav.vue',import.meta.url),'utf8')
 assert.match(shared,/LotusMobileHeader/)
 assert.match(shared,/LotusMobileBottomNav/)
 assert.match(header,/class="lotus-pwa-logo"/)
 assert.match(header,/NavBar/)
 assert.match(bottom,/Tabbar/)
 assert.match(entry,/vant\/lib\/index.css/)
 assert.match(css,/mobile-actions\{grid-template-columns:repeat\(2/)
 assert.match(css,/mobile-submit\{[^}]*min-height:64px/)
 assert.match(app,/class="mobile-line"/)
})
test('Purchases and receipts reuse existing ERP APIs; mobile confirmation before ledger changes',()=>{
 assert.match(app,/buyingAPI\('save_order'/)
 assert.match(app,/stockAPI\('create_draft'/)
 assert.match(app,/stockAPI\('submit_document'/)
 assert.match(app,/receivingAPI\('receive_order'/)
 assert.match(app,/receivingAPI\('receipt_action'/)
 assert.match(app,/client_event_id/)
 assert.match(app,/v-model="confirmed"/)
})
test('all link fields open options on focus and filter while typing',()=>{
 const link=readFileSync(new URL('../src/components/MobileLinkField.vue',import.meta.url),'utf8')
 assert.match(link,/@focus="reveal"/)
 assert.match(link,/@input="changed"/)
 assert.match(link,/role="listbox"/)
 assert.match(link,/\.filter\(r=>norm/)
 const purchase=readFileSync(new URL('../src/components/MobilePurchaseOrderForm.vue',import.meta.url),'utf8')
 assert.match(app,/<MobilePurchaseOrderForm/)
 for(const kind of [':options="storeOptions"',':options="employeeOptions"',':options="supplierOptions"',':options="itemOptions"'])assert.ok((app+purchase).includes(kind),kind)
})
test('purchase is first action and native browser back stays inside PWA',()=>{
 const actions=app.slice(app.indexOf('class="mobile-actions"'),app.indexOf('class="mobile-install"'))
 assert.ok(actions.indexOf('Tạo đơn mua')<actions.indexOf('Nhập theo đơn'))
 assert.match(app,/popstate/)
 assert.match(app,/window\.history\.pushState/)
 assert.match(app,/confirmLeave/)
 assert.match(app,/flush:'sync'/)
})
